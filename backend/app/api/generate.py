def _make_readme(domain: str, files: list[str], failed_checks: list[str]) -> str:
    lines = [
        f"# Fix Pack for {domain}",
        f"Generated by Agentable (https://seo4agent.com) on {date.today().isoformat()}",
        "",
    ]
    if files:
        deploy_map = {
            "robots-patch.txt": f"Merge into https://{domain}/robots.txt",
            ".well-known/security.txt": f"Deploy at https://{domain}/.well-known/security.txt",
            ".well-known/mcp.json": f"Deploy at https://{domain}/.well-known/mcp.json",
            "schema-jsonld.html": "Add the <script> tag inside <head> of your HTML",
            "og-tags.html": "Add the <meta> tags inside <head> of your HTML",
            "llms.txt": f"Deploy at https://{domain}/llms.txt",
        }
        lines += ["## Files included", ""]
        for f in files:
            lines.append(f"- **{f}** — {deploy_map.get(f, 'See file for instructions')}")
        lines.append("")

    lines += ["## Full fix checklist", ""]
    for cid in failed_checks:
        advice = CHECK_ADVICE.get(cid, f"Fix check: {cid}")
        lines.append(f"- [ ] **{cid}**: {advice}")

    lines += ["", "## Re-audit after deploying", f"https://seo4agent.com"]
    return "\n".join(lines)


@router.post("/generate/fix-pack")
async def generate_fix_pack(req: FixPackRequest):
    url = req.url.strip().rstrip("/")
    if not url.startswith("http"):
        url = "https://" + url
    base = _base(url)
    domain = urlparse(url).netloc

    # Fetch site for title/description (needed for OG/schema)
    title, description = "", ""
    async with httpx.AsyncClient(follow_redirects=True) as client:
        html = await _fetch(client, url)
        sitemap_xml = await _fetch(client, f"{base}/sitemap.xml")
        nav: list[tuple[str, str]] = []
        sections: list[str] = []
        if html:
            soup = BeautifulSoup(html, "html.parser")
            og_title = soup.find("meta", property="og:title")
            title_tag = soup.find("title")
            title = _clean(og_title["content"]) if og_title and og_title.get("content") else (
                _clean(title_tag.get_text()) if title_tag else domain)
            og_desc = soup.find("meta", property="og:description")
            meta_desc = soup.find("meta", attrs={"name": "description"})
            description = _clean(og_desc["content"]) if og_desc and og_desc.get("content") else (
                _clean(meta_desc["content"]) if meta_desc and meta_desc.get("content") else "")
            nav = _extract_nav_links(soup, base)
            sections = _extract_sections(soup)
        sitemap_urls = _parse_sitemap(sitemap_xml, base) if sitemap_xml else []

    checks = set(req.failed_checks)
    files: dict[str, str] = {}

    if "l2_robots" in checks or "l0_block" in checks:
        files["robots-patch.txt"] = _make_robots_patch(domain)

    if "l2_securitytxt" in checks:
        files[".well-known/security.txt"] = _make_security_txt(domain)

    if "l4_webmcp" in checks or "l4_mcp" in checks:
        files[".well-known/mcp.json"] = _make_mcp_json(domain)

    if "l1_schema" in checks:
        files["schema-jsonld.html"] = _make_schema_jsonld(domain, title, description)

    if "l1_og" in checks:
        files["og-tags.html"] = _make_og_tags(domain, title, description)

    if "l2_llmstxt" in checks:
        llms_content = _build_llms_txt(url, title, description, nav, sections, sitemap_urls)
        files["llms.txt"] = llms_content

    files["README.md"] = _make_readme(domain, list(files.keys()), req.failed_checks)

    # Build ZIP in memory
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for name, content in files.items():
            zf.writestr(name, content)
    buf.seek(0)

    filename = f"agentable-fixes-{domain}.zip"
    return StreamingResponse(
        buf,
        media_type="application/zip",
        headers={"Content-Disposition": f'attachment; filename="{filename}"'},
    )
