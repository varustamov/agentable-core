from urllib.parse import urlparse, urljoin

router = APIRouter(tags=["generate"])

HEADERS = {
    "User-Agent": "AISEOSetup/1.0 (+https://aiseo.setup; llms-txt-generator)",
    "Accept": "text/html,application/xhtml+xml,*/*;q=0.8",
}
TIMEOUT = httpx.Timeout(12.0, connect=5.0)


class GenerateRequest(BaseModel):
    url: str


def _base(url: str) -> str:
    p = urlparse(url)
    return f"{p.scheme}://{p.netloc}"


def _clean(text: str) -> str:
    return " ".join(text.split()) if text else ""


async def _fetch(client: httpx.AsyncClient, url: str) -> str | None:
    try:
        r = await client.get(url, headers=HEADERS, timeout=TIMEOUT, follow_redirects=True)
        if r.status_code == 200 and "text" in r.headers.get("content-type", ""):
            return r.text
    except Exception:
        pass
    return None


def _extract_nav_links(soup: BeautifulSoup, base: str) -> list[tuple[str, str]]:
    """Extract navigation links as (title, url) pairs."""
    links = []
    seen = set()
    # Try nav elements first, then header links
    for container in soup.select("nav, header"):
        for a in container.find_all("a", href=True):
            href = a["href"].strip()
            text = _clean(a.get_text())
            if not text or len(text) > 60:
                continue
            full = urljoin(base, href)
            if full.startswith(base) and full not in seen:
                seen.add(full)
                links.append((text, full))
    return links[:20]


def _extract_sections(soup: BeautifulSoup) -> list[str]:
    """Extract main section headings."""
    sections = []
    for tag in soup.find_all(["h2", "h3"]):
        text = _clean(tag.get_text())
        if text and 3 < len(text) < 120:
            sections.append(text)
    return sections[:15]


def _parse_sitemap(xml: str, base: str) -> list[str]:
    """Extract URLs from sitemap XML."""
    soup = BeautifulSoup(xml, "html.parser")
    urls = []
    for loc in soup.find_all("loc"):
        url = loc.get_text().strip()
        if url.startswith(base):
            urls.append(url)
    return urls[:50]


def _build_llms_txt(url: str, title: str, description: str,
                    nav: list[tuple[str, str]], sections: list[str],
                    sitemap_urls: list[str]) -> str:
    lines = []
    domain = urlparse(url).netloc

    lines.append(f"# {title or domain}")
    lines.append("")
    if description:
        lines.append(f"> {description}")
        lines.append("")

    lines.append(f"Source: {url}")
    lines.append("")

    if nav:
        lines.append("## Navigation")
        lines.append("")
        for name, href in nav:
            lines.append(f"- [{name}]({href})")
        lines.append("")

    if sections:
        lines.append("## Page Sections")
        lines.append("")
        for s in sections:
            lines.append(f"- {s}")
        lines.append("")

    if sitemap_urls:
        lines.append("## Site Pages")
        lines.append("")
        for u in sitemap_urls[:30]:
            lines.append(f"- {u}")
        lines.append("")

    lines.append("---")
    lines.append("Generated by [Agentable](https://seo4agent.com) — Agent Readiness Auditor")

    return "\n".join(lines)


@router.post("/generate/llms-txt")
async def generate_llms_txt(req: GenerateRequest):
    url = req.url.strip().rstrip("/")
    if not url.startswith("http"):
        url = "https://" + url
    base = _base(url)

    async with httpx.AsyncClient(follow_redirects=True) as client:
        html = await _fetch(client, url)
        sitemap_xml = await _fetch(client, f"{base}/sitemap.xml")

    title = ""
    description = ""
    nav: list[tuple[str, str]] = []
    sections: list[str] = []

    if html:
        soup = BeautifulSoup(html, "html.parser")
        title_tag = soup.find("title")
        title = _clean(title_tag.get_text()) if title_tag else ""
        og_title = soup.find("meta", property="og:title")
        if og_title and og_title.get("content"):
            title = _clean(og_title["content"])

        meta_desc = soup.find("meta", attrs={"name": "description"})
        if meta_desc and meta_desc.get("content"):
            description = _clean(meta_desc["content"])
        og_desc = soup.find("meta", property="og:description")
        if og_desc and og_desc.get("content"):
            description = _clean(og_desc["content"])

        nav = _extract_nav_links(soup, base)
        sections = _extract_sections(soup)

    sitemap_urls: list[str] = []
    if sitemap_xml:
        sitemap_urls = _parse_sitemap(sitemap_xml, base)

    content = _build_llms_txt(url, title, description, nav, sections, sitemap_urls)
    filename = f"llms-{urlparse(url).netloc}.txt"
    return PlainTextResponse(
        content=content,
        headers={"Content-Disposition": f'attachment; filename="{filename}"'},
    )


